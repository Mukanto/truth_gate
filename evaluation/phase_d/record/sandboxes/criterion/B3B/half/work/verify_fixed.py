"""Cross-checks of the FIXED bodies against independent re-implementations (scipy allowed here, in scratch only).

For each case a dataset is generated by this script (own arrays, with the brief's keys and shapes). The reference value
of the statistic is computed by independent code; then the fixed body is run with its last threshold literal replaced
by ref -/+ eps, and must flip from one answer to the other exactly at the reference value.
Never opens or imports a faulty body.
"""
