# B3B-08 Fick correlation corrected
n = 40
co_t = rng.normal(5, 1, n)
ca = rng.normal(18, 1, n)
cv = ca - 5 - 0.3 * (co_t - 5) + rng.normal(0, 0.8, n)
co1 = co_t + rng.normal(0, 0.3, n)
co2 = co_t + rng.normal(0, 0.3, n)
k = 10.0
vo2, do2 = k * co1 * (ca - cv), k * co1 * ca
s2 = np.var(co1 - co2, ddof=1) / 2
Vv = np.var(vo2, ddof=1) - k ** 2 * s2 * np.mean((ca - cv) ** 2)
Vw = np.var(do2, ddof=1) - k ** 2 * s2 * np.mean(ca ** 2)
Cc = np.cov(vo2, do2)[0, 1] - k ** 2 * s2 * np.mean((ca - cv) * ca)
ref = Cc / np.sqrt(Vv * Vw)
allok &= check('B3B-08', dict(cardiac_output=co1, cardiac_output_2=co2, arterial_o2_content=ca,
                              venous_o2_content=cv), ref, 'ge')

