# B3B-06 and B3B-13 Blomqvist adjustment, written independently with per-individual polyfit


def blomqvist(x):
    n, m = x.shape
    t = np.arange(m, dtype=float)
    est = np.array([np.polyfit(t, x[i], 1) for i in range(n)])  # slope, intercept at t = 0
    bh, ah = est[:, 0], est[:, 1]
    ssr = 0.0
    for i in range(n):
        r = x[i] - (ah[i] + bh[i] * t)
        ssr += r @ r
    s2 = ssr / (n * (m - 2))
    sxx = np.sum((t - t.mean()) ** 2)
    tb = t.mean()
    caa = np.var(ah, ddof=1) - s2 * (1 / m + tb ** 2 / sxx)
    cbb = np.var(bh, ddof=1) - s2 / sxx
    cab = np.cov(ah, bh)[0, 1] + s2 * tb / sxx
    return caa, cbb, cab


n, m = 400, 5
alpha = rng.normal(130, 15, n)
