def src_of(lid):
    return open(os.path.join(HALF, 'cases', IDS[lid], 'fixed_body.py'), encoding='utf-8').read()


def run_with(src, d, thr):
    lines = src.rstrip('\n').split('\n')
    i = max(j for j, l in enumerate(lines) if l.startswith('    return bool('))
    lines[i] = re.sub(r'(-?\d+\.\d+)\)$', repr(float(thr)) + ')', lines[i])
    ns = {}
    exec(compile('\n'.join(lines) + '\n', 'variant', 'exec'), ns)
    return ns['criterion'](d)


def check(lid, d, ref, direction):
    """direction: 'ge' (stat >= thr), 'le' (stat <= thr), 'plt' (p < thr, extra coefficient condition inside)."""
    src = src_of(lid)
    eps = max(1e-9, abs(ref) * 1e-7)
    if direction == 'ge':
        a, b = run_with(src, d, ref - eps), run_with(src, d, ref + eps)
        ok = (a is True and b is False)
    elif direction == 'le':
        a, b = run_with(src, d, ref + eps), run_with(src, d, ref - eps)
        ok = (a is True and b is False)
    else:
        a, b = run_with(src, d, ref * (1 + 1e-6)), run_with(src, d, ref * (1 - 1e-6))
        ok = (a is True and b is False)
    print(lid, 'ref=%.10g' % ref, 'flip ok' if ok else 'FLIP FAILED (%r, %r)' % (a, b))
    return ok


